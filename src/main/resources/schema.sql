CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(150) NOT NULL,
 email VARCHAR(180) NOT NULL UNIQUE,
 senha_hash VARCHAR(100) NOT NULL,
 perfil VARCHAR(20) NOT NULL CHECK (perfil IN ('ADMIN','PROFISSIONAL')),
 ativo BOOLEAN NOT NULL DEFAULT TRUE,
 criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS atendimentos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 protocolo VARCHAR(40) UNIQUE,
 nome VARCHAR(180) NOT NULL,
 paciente VARCHAR(180) NOT NULL,
 saram VARCHAR(30) NOT NULL,
 idade VARCHAR(10), bairro VARCHAR(120), residencia VARCHAR(30), celular VARCHAR(30),
 vinculo VARCHAR(80), meio_contato VARCHAR(80), categoria VARCHAR(80), situacao VARCHAR(120),
 tipo VARCHAR(120), classificacao VARCHAR(120), status VARCHAR(20) NOT NULL CHECK (status IN ('Pendente','Resolvido')),
 estado VARCHAR(120), descricao VARCHAR(1500) NOT NULL, encaminhamento VARCHAR(1500),
 criado_por BIGINT NOT NULL REFERENCES usuarios(id), criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, versao INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix_atendimentos_criado_em ON atendimentos(criado_em DESC);
CREATE INDEX IF NOT EXISTS ix_atendimentos_saram ON atendimentos(saram);
CREATE TABLE IF NOT EXISTS evolucoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atendimento_id BIGINT NOT NULL REFERENCES atendimentos(id),
 texto VARCHAR(1500) NOT NULL, status_apos VARCHAR(20) NOT NULL,
 autor_id BIGINT NOT NULL REFERENCES usuarios(id), criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS ix_evolucoes_atendimento ON evolucoes(atendimento_id, criado_em DESC);
